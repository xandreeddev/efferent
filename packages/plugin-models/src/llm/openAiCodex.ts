export const OPENAI_CODEX_API_URL = "https://chatgpt.com/backend-api/codex"

/** A Responses request as the OpenAI client encodes it: the fields the subscription dialect rewrites, every other one passed on. */
const ResponsesRequest = Schema.StructWithRest(
  Schema.Struct({
    input: Schema.optionalKey(Schema.Array(Schema.Json)),
    text: Schema.optionalKey(Schema.Struct({ verbosity: Schema.optionalKey(Schema.Json) })),
    reasoning: Schema.optionalKey(Schema.JsonObject),
    tool_choice: Schema.optionalKey(Schema.Json),
    parallel_tool_calls: Schema.optionalKey(Schema.Json),
  }),
  [Schema.Record(Schema.String, Schema.Json)],
)
type ResponsesRequest = typeof ResponsesRequest.Type
const decodeRequest = Schema.decodeUnknownOption(ResponsesRequest)
const decodeRequestText = Schema.decodeUnknownOption(Schema.fromJsonString(ResponsesRequest))

/** A system or developer message: its text is the subscription's `instructions`. */
const InstructionMessage = Schema.Struct({
  role: Schema.Literals(["developer", "system"]),
  content: Schema.Union([Schema.String, Schema.Array(Schema.Json)]),
})
const decodeInstruction = Schema.decodeUnknownOption(InstructionMessage)
const decodeTextPart = Schema.decodeUnknownOption(Schema.Struct({ text: Schema.String }))

const instructionText = (message: Schema.Json): ReadonlyArray<string> =>
  Option.match(decodeInstruction(message), {
    onNone: () => [],
    onSome: ({ content }) => Predicate.isString(content)
      ? [content]
      : content.flatMap((part) => Option.toArray(Option.map(decodeTextPart(part), ({ text }) => text))),
  })

const subscriptionBody = (value: ResponsesRequest, reasoningEffort: Option.Option<ReasoningEffortType>): Schema.JsonObject => {
  const input = value.input ?? []
  const instructions = input.flatMap(instructionText).join("\n\n")
  const conversationalInput = input.filter((message) => instructionText(message).length === 0)
  // ChatGPT's subscription endpoint is not the public Responses API and
  // rejects this otherwise-standard field. Agent timeouts/step limits remain
  // the execution bound.
  const supported = Object.fromEntries(
    Object.entries(value).filter(([key]) => key !== "max_output_tokens"),
  )
  return {
    ...supported,
    store: false,
    stream: true,
    instructions: instructions.length > 0 ? instructions : "You are a helpful assistant.",
    input: conversationalInput,
    // The subscription dialect accepts verbosity but rejects/derails the
    // public API's nested text.format object generated by the SDK.
    text: { verbosity: value.text?.verbosity ?? "low" },
    include: ["reasoning.encrypted_content"],
    tool_choice: value.tool_choice ?? "auto",
    parallel_tool_calls: value.parallel_tool_calls ?? true,
    ...Option.match(reasoningEffort, {
      onNone: () => ({}),
      onSome: (effort) => ({ reasoning: { ...value.reasoning, effort, summary: "auto" } }),
    }),
  }
}

/**
 * Translate the standard Responses request into the Codex subscription
 * dialect. A body that is not a Responses request object reads as an empty
 * one.
 */
export const toOpenAiCodexRequestBody = (
  body: unknown,
  reasoningEffort?: ReasoningEffortType,
): Schema.JsonObject => subscriptionBody(Option.getOrElse(decodeRequest(body), () => ({})), Option.fromNullishOr(reasoningEffort))

const transformRequest = (
  accountId: string,
  reasoningEffort: Option.Option<ReasoningEffortType>,
) => (request: HttpClientRequest.HttpClientRequest): HttpClientRequest.HttpClientRequest => {
  const withHeaders = request.pipe(
    HttpClientRequest.setHeaders({
      "chatgpt-account-id": accountId,
      // Part of the protocol: the backend keys model entitlement to the
      // OAuth client/originator pair (Luna otherwise returns a misleading 404).
      originator: OPENAI_CODEX_ORIGINATOR,
      "OpenAI-Beta": "responses=experimental",
      accept: "text/event-stream",
    }),
  )
  if (request.body._tag !== "Uint8Array") return withHeaders
  return Option.match(
    decodeRequestText(new TextDecoder().decode(request.body.body)),
    {
      onNone: () => withHeaders,
      onSome: (decoded) => HttpClientRequest.bodyJsonUnsafe(
        withHeaders,
        subscriptionBody(decoded, reasoningEffort),
      ),
    },
  )
}

/** The HTTP status an Effect provider error carries, when it has one. */
const responseStatus = (error: unknown): number | undefined =>
  AiError.isAiError(error) && "http" in error.reason ? error.reason.http?.response?.status : undefined

/**
 * Refine structured subscription errors before the legacy protocol fallback.
 * Keep concrete reason classes and HTTP/provider evidence; explicit semantic
 * stamps prevent a protocol failure from becoming a model-output corrective.
 */
export const mapOpenAiCodexError = <E>(_model: string, error: E): E | AiError.AiError => {
  if (!AiError.isAiError(error)) return error
  const metadata = "metadata" in error.reason ? error.reason.metadata : {}
  const engine = Object.hasOwn(metadata, ENGINE_KEY) ? metadata[ENGINE_KEY] : undefined
  if (Predicate.isObject(engine) && Object.hasOwn(engine, "failure") && Option.isSome(Schema.decodeUnknownOption(ModelFailureStamp)(engine))) return error
  const classified = classifyAiError(error, "openai")
  if (Option.exists(modelFailureOf(classified), (kind) => kind !== "Unknown")) return classified
  return responseStatus(classified) === 200 ? stampAiErrorFailure(classified, "InvalidResponse") : classified
}

export const makeOpenAiCodexLanguageModel = (args: {
  readonly model: string
  readonly accessToken: Redacted.Redacted<string>
  readonly accountId: string
  /** How the WebSocket reaches ChatGPT (`ModelsTransport.webSocketAgent`); default: directly. */
  readonly webSocketProxy?: Option.Option<WebSocketProxy>
}) =>
  Effect.all({
    cacheKey: Effect.service(CurrentPromptCacheKey),
    policy: Effect.service(CurrentModelCallPolicy),
    sessions: Effect.flatMap(Effect.service(CurrentOpenAiCodexSessions), Option.match({
      onSome: Effect.succeed,
      onNone: () => makeOpenAiCodexSessions(),
    })),
  }, { concurrency: 1 }).pipe(
    Effect.flatMap(({ cacheKey, policy, sessions }) =>
      OpenAiClient.make({
        apiKey: args.accessToken,
        apiUrl: OPENAI_CODEX_API_URL,
        transformClient: () => makeOpenAiCodexWebSocketHttpClient(args.webSocketProxy ?? Option.none(), Option.some(sessions)).pipe(
          // Replacing the transport also replaces OpenAiClient's underlying
          // request pipeline, so reproduce its base URL + bearer steps here.
          HttpClient.mapRequest((request) =>
            transformRequest(
              args.accountId,
              Option.map(policy, (value) => value.effort),
            )(
              request.pipe(
                HttpClientRequest.prependUrl(OPENAI_CODEX_API_URL),
                HttpClientRequest.bearerToken(args.accessToken),
              ),
            ),
          ),
          // The final WebSocket request, including subscription headers/body,
          // uses the same request budget and guarded readers as native HTTP.
          // Only this existing SDK erasure boundary narrows the wider typed
          // response/client channels; runtime AiError values pass unchanged.
          (client) => resilientHttpClient(client, {
            protocol: "openai",
            adaptResponse: (response) => response as HttpClientResponse.HttpClientResponse,
          }) as HttpClient.HttpClient.With<HttpClientError.HttpClientError>,
        ),
      }).pipe(
        Effect.map(withOpenAiFailures),
        Effect.flatMap((client) =>
          OpenAiLanguageModel.make({
            model: args.model,
            config: {
              strictJsonSchema: false,
              store: false,
              prompt_cache_key: Option.getOrElse(cacheKey, () => "efferent"),
              text: { verbosity: "low" },
              ...Option.match(policy, {
                onNone: () => ({}),
                onSome: (value) => ({
                  ...(value.maxOutputTokens === undefined
                    ? {}
                    : { max_output_tokens: value.maxOutputTokens }),
                  reasoning: {
                    // @effect/ai-openai's generated union predates none/xhigh/max;
                    // transformRequest restores the exact effort on the wire.
                    effort: value.effort === "xhigh" || value.effort === "max"
                      ? "high"
                      : value.effort === "none"
                        ? "low"
                        : value.effort,
                    summary: "auto" as const,
                  },
                }),
              }),
            },
          }).pipe(Effect.provideService(OpenAiClient.OpenAiClient, client)),
        ),
        // The ChatGPT subscription endpoint is stream-only. Expose the full
        // LanguageModel port by deriving settled calls from that same stream,
        // so non-streaming use cases do not accidentally send stream:false.
        Effect.map((streaming) => {
          const selection = new ModelSelection({ provider: ProviderId.make("openai-codex"), modelId: ModelId.make(args.model) })
          const streamText = ((options: unknown) =>
            withModelRequestStream("Stream", selection, streaming.streamText(options as never)).pipe(
              Stream.catch((error) => isTurnError(error) ? Stream.die(error) : Stream.fail(mapOpenAiCodexError(args.model, error))),
            )) as LanguageModel.LanguageModel["streamText"]
          const model = {
            ...streaming,
            streamText,
            generateObject: ((options: unknown) => withModelRequestCall("Object", selection, streaming.generateObject(options as never)).pipe(Effect.catch((error) => isTurnError(error) ? Effect.die(error) : Effect.fail(error)))) as never,
            generateText: ((options: unknown) =>
              withModelRequestCall("Text", selection, foldStreamParts(streamText(options as never), () => Effect.void)).pipe(
                Effect.map((turn) => new LanguageModel.GenerateTextResponse(turn.content as never)),
                Effect.catch((error) => isTurnError(error) ? Effect.die(error) : Effect.fail(error)),
              )) as never,
          } satisfies LanguageModel.LanguageModel
          return describeModel(model, {
            provider: "openai-codex", model: args.model,
            settings: {
              strictJsonSchema: false, store: false, stream: true,
              prompt_cache_key: Option.getOrElse(cacheKey, () => "efferent"),
              text: { verbosity: "low" },
              ...Option.match(policy, { onNone: () => ({}), onSome: (value) => ({ reasoning: { effort: value.effort, summary: "auto" } }) }),
            },
          })
        }),
      ),
    ),
  )
